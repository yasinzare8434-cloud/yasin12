// ─── Helpers ───────────────────────────────────────────
function _dai_cat($name, $slug, $parent_id = 0) {
    $existing = get_term_by('slug', $slug, 'category');
    if ($existing) return $existing->term_id;
    $args = ['slug' => $slug];
    if ($parent_id) $args['parent'] = $parent_id;
    $r = wp_insert_term($name, 'category', $args);
    return is_wp_error($r) ? 0 : (int)$r['term_id'];
}

function _dai_page($title, $slug, $content) {
    $existing = get_page_by_path($slug);
    if ($existing) return $existing->ID;
    return wp_insert_post([
        'post_type'    => 'page',
        'post_title'   => $title,
        'post_name'    => $slug,
        'post_content' => $content,
        'post_status'  => 'publish',
        'comment_status' => 'closed',
    ]);
}

function _dai_post($title, $slug, $content, $cat_id) {
    $existing = get_page_by_path($slug, OBJECT, 'post');
    if ($existing) return $existing->ID;
    return wp_insert_post([
        'post_type'    => 'post',
        'post_title'   => $title,
        'post_name'    => $slug,
        'post_content' => $content,
        'post_status'  => 'publish',
        'post_category' => [$cat_id],
        'comment_status' => 'open',
    ]);
}

